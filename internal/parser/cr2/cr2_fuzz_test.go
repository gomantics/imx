package cr2

import (
	"bytes"
	"testing"
)

// FuzzCR2Parse tests the CR2 parser with random inputs to catch panics and edge cases.
func FuzzCR2Parse(f *testing.F) {
	// Seed 1: Minimal valid CR2 with empty IFD (exercises basic parsing)
	// Little-endian: II 42 0 + IFD offset + CR2 magic + version + padding + empty IFD
	f.Add([]byte{
		0x49, 0x49, 0x2A, 0x00, // TIFF header: "II" + 42
		0x10, 0x00, 0x00, 0x00, // IFD offset = 16
		0x43, 0x52, // CR2 magic "CR"
		0x02, 0x00, // Version 2.0
		0x00, 0x00, 0x00, 0x00, // Padding to offset 16
		0x00, 0x00, // 0 entries
		0x00, 0x00, 0x00, 0x00, // Next IFD = 0
	})

	// Seed 2: CR2 with single tag (exercises tag reading)
	// IFD with one tag: ImageWidth = 100
	f.Add([]byte{
		0x49, 0x49, 0x2A, 0x00, // TIFF header
		0x10, 0x00, 0x00, 0x00, // IFD offset = 16
		0x43, 0x52, 0x02, 0x00, // CR2 magic + version
		0x00, 0x00, 0x00, 0x00, // Padding
		0x01, 0x00, // 1 entry
		// Tag: ImageWidth (0x0100), type SHORT (3), count 1, value 100
		0x00, 0x01, 0x03, 0x00, 0x01, 0x00, 0x00, 0x00, 0x64, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, // Next IFD = 0
	})

	// Seed 3: CR2 with multiple tags of different types (exercises type handling)
	f.Add([]byte{
		0x49, 0x49, 0x2A, 0x00, // TIFF header
		0x10, 0x00, 0x00, 0x00, // IFD offset = 16
		0x43, 0x52, 0x02, 0x00, // CR2 magic + version
		0x00, 0x00, 0x00, 0x00, // Padding
		0x03, 0x00, // 3 entries
		// Tag 1: ImageWidth (0x0100), SHORT, count 1, value 100
		0x00, 0x01, 0x03, 0x00, 0x01, 0x00, 0x00, 0x00, 0x64, 0x00, 0x00, 0x00,
		// Tag 2: ImageHeight (0x0101), SHORT, count 1, value 200
		0x01, 0x01, 0x03, 0x00, 0x01, 0x00, 0x00, 0x00, 0xC8, 0x00, 0x00, 0x00,
		// Tag 3: Make (0x010F), ASCII, count 6, offset to data
		0x0F, 0x01, 0x02, 0x00, 0x06, 0x00, 0x00, 0x00, 0x4A, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, // Next IFD = 0
		// String data at offset 74 (0x4A): "Canon\0"
		0x43, 0x61, 0x6E, 0x6F, 0x6E, 0x00,
	})

	// Seed 4: Big-endian variant with tags
	f.Add([]byte{
		0x4D, 0x4D, 0x00, 0x2A, // TIFF header: "MM" + 42
		0x00, 0x00, 0x00, 0x10, // IFD offset = 16 (big-endian)
		0x43, 0x52, 0x02, 0x01, // CR2 magic + version 2.1
		0x00, 0x00, 0x00, 0x00, // Padding
		0x00, 0x01, // 1 entry (big-endian)
		// Tag: ImageWidth, SHORT, count 1, value 100 (all big-endian)
		0x01, 0x00, 0x00, 0x03, 0x00, 0x00, 0x00, 0x01, 0x00, 0x64, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, // Next IFD = 0
	})

	// Seed 5: CR2 with sub-IFD pointer (exercises sub-IFD parsing)
	f.Add([]byte{
		0x49, 0x49, 0x2A, 0x00, // TIFF header
		0x10, 0x00, 0x00, 0x00, // IFD offset = 16
		0x43, 0x52, 0x02, 0x00, // CR2 magic + version
		0x00, 0x00, 0x00, 0x00, // Padding
		0x01, 0x00, // 1 entry in IFD0
		// Tag: ExifIFD pointer (0x8769), LONG, count 1, offset to sub-IFD
		0x69, 0x87, 0x04, 0x00, 0x01, 0x00, 0x00, 0x00, 0x32, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, // Next IFD = 0
		// Sub-IFD at offset 50 (0x32)
		0x01, 0x00, // 1 entry in ExifIFD
		// Tag: ISOSpeedRatings (0x8827), SHORT, count 1, value 100
		0x27, 0x88, 0x03, 0x00, 0x01, 0x00, 0x00, 0x00, 0x64, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, // Next sub-IFD = 0
	})

	// Seed 6: CR2 with rational value (exercises rational parsing)
	f.Add([]byte{
		0x49, 0x49, 0x2A, 0x00, // TIFF header
		0x10, 0x00, 0x00, 0x00, // IFD offset = 16
		0x43, 0x52, 0x02, 0x00, // CR2 magic + version
		0x00, 0x00, 0x00, 0x00, // Padding
		0x01, 0x00, // 1 entry
		// Tag: XResolution (0x011A), RATIONAL, count 1, offset to data
		0x1A, 0x01, 0x05, 0x00, 0x01, 0x00, 0x00, 0x00, 0x32, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, // Next IFD = 0
		// Rational data at offset 50: 72/1 (numerator=72, denominator=1)
		0x48, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
	})

	f.Fuzz(func(t *testing.T, data []byte) {
		defer func() {
			if r := recover(); r != nil {
				t.Errorf("Parser panicked: %v", r)
			}
		}()

		reader := bytes.NewReader(data)
		parser := New()

		// Just call Parse - we don't care about errors, only panics
		_, _ = parser.Parse(reader)
	})
}
